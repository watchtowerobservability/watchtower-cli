package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"os"
	"regexp"
	"strings"
)

const gatusUsage = "usage: wtctl gatus config --api <url> --key <key> --project <slug> --project-id <prj_...> [--env <name|id>] [--public-url <url>] [--group <g>]"

type gatusToken struct {
	EnvID     *string `json:"env_id"`
	Service   *string `json:"service"`
	Name      string  `json:"name"`
	RevokedAt *string `json:"revoked_at"`
}

var keyUnsafe = regexp.MustCompile(`[^A-Za-z0-9-]+`)

// gatusMain is `wtctl gatus ...`.
func gatusMain(ctx context.Context, args []string, out io.Writer) error {
	if len(args) < 1 || args[0] != "config" {
		return errors.New(gatusUsage)
	}
	fs := flag.NewFlagSet("gatus config", flag.ContinueOnError)
	var api, key, project, projectID, env, pub, group string
	fs.StringVar(&api, "api", "", "API base URL")
	fs.StringVar(&key, "key", os.Getenv("WT_API_KEY"), "API key; default $WT_API_KEY")
	fs.StringVar(&project, "project", "", "project slug (as in /v1/health/{project})")
	fs.StringVar(&projectID, "project-id", "", "project id (prj_...) for the management API; required")
	fs.StringVar(&env, "env", "", "only health tokens of this environment (name or id)")
	fs.StringVar(&pub, "public-url", "", "URL Gatus polls (default: --api)")
	fs.StringVar(&group, "group", "watchtower", "Gatus group of the generated endpoints")
	if err := fs.Parse(args[1:]); err != nil {
		return err
	}
	if api == "" || key == "" || project == "" {
		return errors.New(gatusUsage)
	}
	// No route resolves a slug to an id (projects list per org only), and /v1/projects/{prj} needs the id.
	if !strings.HasPrefix(projectID, "prj_") {
		return errors.New("--project-id (prj_...) is required: the API addresses projects by id, and --project is only the slug used in health URLs")
	}
	if pub == "" {
		pub = api
	}
	base := strings.TrimRight(api, "/") + "/v1/projects/" + url.PathEscape(projectID)
	var envs struct{ Data []struct{ ID, Name string } }
	if err := call(ctx, http.MethodGet, base+"/environments?limit=200", key, nil, &envs); err != nil {
		return err
	}
	names := map[string]string{}
	envID := ""
	for _, e := range envs.Data {
		names[e.ID] = e.Name
		if e.Name == env || e.ID == env {
			envID = e.ID
		}
	}
	if env != "" && envID == "" {
		return fmt.Errorf("no environment %q in the project", env)
	}
	var toks []gatusToken
	for cursor := ""; ; {
		var page struct {
			Data       []gatusToken `json:"data"`
			NextCursor *string      `json:"next_cursor"`
		}
		u := base + "/health-tokens?limit=100"
		if cursor != "" {
			u += "&cursor=" + url.QueryEscape(cursor)
		}
		if err := call(ctx, http.MethodGet, u, key, nil, &page); err != nil {
			return err
		}
		toks = append(toks, page.Data...)
		if page.NextCursor == nil || *page.NextCursor == "" {
			break
		}
		cursor = *page.NextCursor
	}
	renderGatus(out, gatusParams{project: project, group: group, pub: strings.TrimRight(pub, "/"), envID: envID, names: names}, toks)
	return nil
}

type gatusParams struct {
	project, group, pub, envID string
	names                      map[string]string
}

// renderGatus writes the Gatus YAML. Secrets never appear: each endpoint reads its health token
// from ${WT_HEALTH_TOKEN_<n>}, which the operator sets from the one-time token value.
func renderGatus(out io.Writer, p gatusParams, toks []gatusToken) {
	fmt.Fprintf(out, "# Generated by wtctl gatus config. Set each WT_HEALTH_TOKEN_<n> from the value shown once when the token was created.\nendpoints:\n")
	n := 0
	for _, t := range toks {
		if t.RevokedAt != nil || (p.envID != "" && (t.EnvID == nil || *t.EnvID != p.envID)) {
			continue
		}
		n++
		path, label := "/v1/health/"+url.PathEscape(p.project), p.project
		if t.EnvID != nil && p.names[*t.EnvID] != "" {
			path += "/" + url.PathEscape(p.names[*t.EnvID])
			label += "-" + p.names[*t.EnvID]
			if t.Service != nil && *t.Service != "" {
				path += "/" + url.PathEscape(*t.Service)
				label += "-" + *t.Service
			}
		}
		fmt.Fprintf(out, "  # token %d: %q\n  - name: %q\n    group: %q\n    url: %q\n    interval: 30s\n    headers:\n      Authorization: \"Bearer ${WT_HEALTH_TOKEN_%d}\"\n    conditions:\n      - \"[STATUS] == 200\"\n      - \"[BODY].status == up\"\n",
			n, t.Name, label, p.group, p.pub+path, n)
	}
	if n == 0 {
		fmt.Fprint(out, "  []\n")
	}
	// The external endpoints receive state pushed by Watchtower (receiver kind gatus_push): one
	// for the project's alerts, one heartbeat the notifier refreshes every 60 s.
	fmt.Fprintf(out, "external-endpoints:\n")
	// Only the self endpoint has a heartbeat: alert state is pushed on change, not periodically.
	fmt.Fprintf(out, "  - name: %q\n    group: %q\n    token: \"${WT_GATUS_ALERTS_TOKEN}\"\n", keyUnsafe.ReplaceAllString(p.project, "-")+"-alerts", p.group)
	fmt.Fprintf(out, "  - name: \"self\"\n    group: %q\n    token: \"${WT_GATUS_SELF_TOKEN}\"\n    heartbeat:\n      interval: 3m\n", p.group)
}
